/* ---------- 初始化：为每条条文生成唯一 id 与归属信息 ---------- */
(function initData() {
  DATA.levels.forEach(level => {
    (level.subjects || []).forEach(subject => {
      subject.passages.forEach((p, i) => {
        p.id = p.id || `${level.id}-${subject.id}-${i}`;
        p.levelId = level.id;
        p.subjectId = subject.id;
        p.subjectName = subject.name;
      });
    });
  });
})();

/* ---------- 导出便捷索引 ---------- */
const ALL_PASSAGES = (() => {
  const out = [];
  DATA.levels.forEach(level => {
    (level.subjects || []).forEach(subject => {
      subject.passages.forEach(p => out.push(p));
    });
  });
  return out;
})();

const PASSAGE_MAP = (() => {
  const m = {};
  ALL_PASSAGES.forEach(p => { m[p.id] = p; });
  return m;
})();